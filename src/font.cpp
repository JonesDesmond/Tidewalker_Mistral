void Font5x7::init() {
    for (int i = 0; i < 128; i++) {
        const GlyphDef* def = nullptr;
        char c = (char)i;
        if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
        for (const GlyphDef& g : GLYPHS) if (g.c == c) { def = &g; break; }
        if (!def) { for (const GlyphDef& g : GLYPHS) if (g.c == '?') { def = &g; break; } }
        if (!def) { for (int k = 0; k < 5; k++) cols[i][k] = 0; continue; }
        for (int col = 0; col < 5; col++) {
            uint8_t b = 0;
            for (int row = 0; row < 7; row++)
                if (def->rows[row][col] == '#') b |= (uint8_t)(1u << row);
            cols[i][col] = b;
        }
    }
    loaded = true;
}
